package modi.backend.ingestionv2.common.queue;

/**
 * 대기열에서 꺼낸 이벤트를 무엇이 처리할지.
 *
 * <ul>
 *   <li>운영 기본은 {@link #REAL} - 도메인 핸들러 여섯이 그대로 등록되고 각자 자기 벤더를 부른다</li>
 *   <li>{@link #STUB} 은 부하 실험 비교용 - 도메인 핸들러를 통째로 내리고 지연만 흉내내는 빈 하나를 대신 등록한다.
 *       배달 계층의 처리량과 배분만 재는 무대에서 외부 유료 호출이 한 건도 나가지 않게 하는 장치다</li>
 *   <li>고르는 자리가 라우터가 아니라 빈 등록 - 실제 핸들러가 빈으로 살아 있으면 회수·재전달 같은
 *       다른 경로에서 되살아날 여지가 남는다</li>
 * </ul>
 */
public enum ConsumeHandler {

	/** 도메인 핸들러 여섯이 등록된다. 운영 값. */
	REAL,

	/** 도메인 핸들러 대신 지연만 흉내내는 빈 하나가 등록된다(부하 실험 비교용). */
	STUB
}
