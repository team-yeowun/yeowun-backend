-- 전시 count 커버링 인덱스 (STEP 5b) — "필터를 좁히는 인덱스"도 "정렬을 대신하는 인덱스"도 아니다.
-- 목표는 하나뿐이다: count가 <b>테이블을 건드리지 않게</b> 한다.
--
-- ── 왜 이게 유일하게 듣는 수단인가 ────────────────────────────────────────────
-- count는 ORDER BY도 LIMIT도 없고, 진행 중 술어가 65.5%를 통과한다(V48 주석의 선택도 실측).
-- 그래서 "행을 좁히는" 인덱스는 원리적으로 못 만든다 — V47·V48이 그걸 실측으로 확인했고
-- STEP 5의 후보 4종(P1 (region,category,end_date,id) 포함)도 전부 효과 0이었다.
-- 남은 축은 <b>세는 단위를 줄이는 것</b>이다: 술어에 필요한 컬럼 전부를 인덱스에 담으면
-- MySQL은 167MB 클러스터드 인덱스 대신 25.6MB 보조 인덱스만 훑는다(Using index).
--   500,174행 실측(버퍼풀 128M, MySQL 8.4.10, 3회 최소값):
--     무필터 count     906.8ms →  138.4ms   (6.6배)
--     무료 count       933.0ms →  143.2ms   (6.5배)
--     지역 count       920.3ms →   61.1ms   (15.1배)
--     지역+무료 count  921.1ms →   64.6ms   (14.3배)
--     키워드 count   1,284.9ms → 1,268.7ms  (변화 없음 — 아래 "못 하는 것")
--
-- ── 컬럼 구성: 왜 이 7개인가 (선행 2개가 선택도 0인데도 넣은 이유) ─────────────
-- 실측 선택도(500,174행):
--     type='CATALOG'        고유값 1개  → 100.0%   거르는 게 없다
--     deleted_at IS NULL                  100.0%   거르는 게 없다
--     region                고유값 16개  SEOUL 36.74% · SEJONG/GWANGJU 각 0.32%
--     category              고유값 1개              이 데이터셋에서는 0, 앱은 IN으로 거른다
--     is_free                            72.8%
--     start_date/end_date   범위 술어(진행 중 판정)
-- 선행 2개는 <b>좁히려고</b> 넣은 게 아니라 <b>커버링을 완성하려고</b> 넣었다. 빼 보면 알 수 있다 —
-- (region, category, is_free, start_date, end_date) 5컬럼 변형을 실측했더니:
--     크기 21.5MB(3.9MB 절약) · 생성 1.76s
--     무필터 count 999.4ms · 지역 count 1,043.2ms   ← 개선 0
--     EXPLAIN의 possible_keys에 <b>아예 들어오지 못한다</b>
-- 술어에 type·deleted_at이 있으므로 그 둘이 인덱스에 없으면 행마다 테이블을 찾아가야 하고,
-- 그러면 풀 스캔이 더 싸다. 즉 3.9MB를 아끼면 인덱스가 <b>완전히 쓸모없어진다</b>.
--
-- ── 컬럼 순서: 등치·IN 축을 전부 범위 앞에 (실측으로 기각한 변형이 있다) ───────
-- 순서 = [항상 참인 등치 2개] → [필터 축 3개: region → category → is_free] → [범위 2개]
--   · 범위(start_date/end_date)를 맨 뒤로: 범위 뒤에 오는 컬럼은 더 이상 스캔 구간을 좁히지 못한다.
--   · region을 필터 축 선두로: 사용자 결정 2("지역만 고르는 게 가장 많다"). 지역 등치가 범위보다
--     앞에 있어 스캔 구간이 SEOUL 몫으로 줄어든다 — 지역 count 138.4ms → 61.1ms.
--   · 실측 기각: 같은 7컬럼에서 region만 <b>맨 뒤</b>로 옮기면(type,deleted_at,category,is_free,
--     start_date,end_date,region) 무필터 280.6ms · 지역 191.0ms · 지역+무료 159.4ms —
--     채택안(138.4 / 61.1 / 64.6)보다 2.0~3.1배 느리다. 크기는 같다.
--     (무필터까지 2배 느려지는 메커니즘은 완전히 설명하지 못했다 — 스킵 스캔의 하위 구간 수가
--      달라지는 것으로 보이나 단정하지 않는다. 순서 선택은 실측 결과로 한다.)
--   · 이 데이터셋의 category는 고유값 1개라 순서상 어디에 둬도 같다. 앱이 category IN (…)으로
--     거르므로 커버링을 유지하려면 <b>담기는 것 자체</b>가 필요하다.
--
-- ── 기존 인덱스와의 관계 ──────────────────────────────────────────────────────
-- idx_exhibitions_type_owner(type, owner_id)의 접두사 type을 삼킨다. 그래도 남긴다 —
-- 관리자 타입별 집계의 유일한 후보이고, 이 인덱스는 owner_id를 담지 않아 대체가 아니다.
-- V48의 정렬 인덱스 2개(start_id·end_id)와는 역할이 겹치지 않는다(그쪽은 ORDER BY 담당).
--
-- ── 대가: 목록 계획을 망칠 수단을 옵티마이저에게 준다 (반드시 함께 읽을 것) ────
-- 이 인덱스가 생기면 옵티마이저의 결합 선택도 추정이 붕괴한다 — 진행 중 술어 통과 행 추정이
-- 260,018 → 42로, 비용이 20,921 → 0.0677로 떨어진다. 그 추정이면 "정렬 인덱스를 앞에서부터
-- 훑으면 21건이 금방 찬다"가 합리적으로 보여 범위 스캔을 포기하고, 실제로는 이미 종료된 전시
-- 151,546행을 걷는다(0.8ms → 622ms 실측).
--   · <b>앱의 목록 쿼리(전 컬럼 SELECT)에서는 이 전환이 500k에서 재현되지 않았다</b> —
--     15개 경로 전부 2ms 이하를 유지했다(S1 0.58 · S2 0.74 · 배너 0.51 · 키워드 49.9ms).
--     위 622ms는 좁은 SELECT 목록(e.id만)에서 재현된다.
--   · <b>붕괴의 방아쇠는 볼륨이 아니라 select 목록이다</b>(STEP 5b 검증에서 구조적으로 확정).
--     스위치는 컬럼 수가 아니라 "쿼리 전체가 이 인덱스로 커버 가능한가"다
--     (`e.id,e.start_date` → 붕괴 / `e.id,e.title` → 정상. title이 인덱스 밖이라서다).
--     앱의 슬라이스는 19컬럼이고 그중 9개가 이 인덱스 밖이라 <b>커버 불가 → 안전한 쪽</b>이다.
--     1M에서도 같다: 좁은 목록 11,370ms vs 앱 목록 0.61ms.
--     → <b>그래서 목록 projection을 좁히는 변경(예: id만 뽑는 최적화)이 이 인덱스와 만나면
--        700~18,000배 후퇴한다.</b> 목록 select 목록을 줄이려는 사람이 이 주석을 봐야 한다.
--   · 목록 경로에는 정렬축별 <b>{@code USE INDEX}</b>가 실려 계획이 못 박혀 있다
--     (→ ExhibitionQueryRepositoryImpl.SORT_INDEX / ExhibitionListIndexHintTest).
--     <b>NO_INDEX 옵티마이저 힌트가 아니다</b> — Hibernate MySQL 방언이 addQueryHint를
--     테이블 힌트로 렌더해서 그 형태는 문법 오류로 죽는다.
--     ⚠ 이 힌트의 측정된 이득은 500k·1M 모두 <b>0</b>이다(옵티마이저가 힌트 없이도 같은 계획을 고른다).
--       계획 고정 목적으로만 남아 있으므로 <b>제거 후보</b>다 — 판단 근거는 _workspace/step5b_guard.md.
--   · 히스토그램은 해법이 아니다 — 516ms → 286ms(기준선의 400배). STEP 5 검증 실측.
--
-- ── 이 인덱스가 못 하는 것 ────────────────────────────────────────────────────
-- 키워드 count(1,285ms)는 그대로다. 술어가 lower(title) LIKE '%…%' <b>선행 와일드카드</b> +
-- exhibition_place 이름 서브쿼리라 어떤 B-tree도 붙지 못한다. 원리적 한계이고
-- 07장 트리거를 이 경로에서 해제하려면 별도 수단(전문 검색·요약 테이블)이 필요하다.
--
-- ── 생성 소요·크기 (실측) ─────────────────────────────────────────────────────
--     500,174행   2.25s   25.6MB
--   1,000,348행   4.34s   50.7MB   ← 실 테이블 복제본(probe)에서 측정, 보조 인덱스 없는 상태
-- 부팅 시 Flyway에 얹힌다. 같은 부팅에서 V49 백필(1M에서 약 27~40초 예상, 미확정)과 합쳐지므로
-- run.sh 헬스체크 120초 예산 안이지만 여유가 크지 않다 — 부팅 로그의 마이그레이션 종료 시각을 확인할 것.
--
-- ── 되돌리기 ──────────────────────────────────────────────────────────────────
--   drop index idx_exhibitions_count_cover on exhibitions;
--
--   ⚠ <b>이 인덱스와 목록 힌트는 한 쌍이 아니다. 서로 다른 인덱스를 가리킨다.</b>
--     · 이 인덱스(count_cover)를 지우는 것은 안전하다 — 힌트는 이걸 가리키지 않는다.
--       count가 느려질 뿐이고 목록은 그대로다.
--     · 🔴 <b>그러나 V48의 정렬 인덱스(idx_exhibitions_start_id·_end_id·view_count)는 지우면 안 된다.</b>
--       목록 SQL에 {@code USE INDEX}로 이름이 박혀 있어, 지우면 MySQL이 조용히 무시하지 않고
--       <b>ERROR 1176으로 하드 실패한다 → 전 목록 경로가 런타임 500</b>(STEP 5b 검증 실측).
--       지우려면 ExhibitionQueryRepositoryImpl의 힌트 주입을 <b>먼저</b> 제거하라.
--       그 안전장치가 ExhibitionListIndexHintTest다(인덱스 실존까지 검사한다).
create index idx_exhibitions_count_cover
    on exhibitions (type, deleted_at, region, category, is_free, start_date, end_date);
